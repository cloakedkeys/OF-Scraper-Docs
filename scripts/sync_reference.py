#!/usr/bin/env python3
"""Copy the fork's reference/ pages into this docs repo's reference/ folder.

Usage: python scripts/sync_reference.py PATH_TO_FORK_CHECKOUT

Copies the generated reference pages. Applies the docs-site adaptations:
  - relative links to anything outside reference/ become absolute GitHub links
  - the "Generated by ... Don't edit by hand" comment becomes a comment
    pointing at this script
  - links within and between these pages point at GitBook's heading ids
Running it twice changes nothing the second time.

reference/README.md (the landing page) and reference/how-it-works.md are
written by hand for the docs site and are not copied. When the fork's
reference/README.md changes, update how-it-works.md to match.
reference/hooks.md is copied by hand from the fork's reference/hooks.md,
with the same link rewriting; this script doesn't copy it.
"""
import posixpath
import re
import sys
from pathlib import Path

REPO = "https://github.com/cloakedkeys/OF-Scraper-Community/blob/main/"
GENERATED = [
    "cli.md",
    "config.md",
    "env.md",
    "env-ratelimits.md",
    "env-urls.md",
    "env-unused.md",
    "placeholders.md",
    "database.md",
]
# Pages that links may point at without being rewritten to GitHub.
PAGES = ["README.md", "how-it-works.md", *GENERATED]

# An HTML comment, so it warns anyone editing the file without showing on the site.
NOTE = (
    "---\n"
    "layout:\n"
    "  width: wide\n"
    "---\n\n"
    "<!-- Copied from the fork's reference/ folder. Don't edit by hand: "
    "edit the fork and run scripts/sync_reference.py. -->\n"
)
COMMENT = re.compile(r"\A<!-- Generated by [^\n]*Don't edit by hand[^\n]*-->\n\n?")

LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def fix_link(m):
    target = m.group(2)
    if re.match(r"^([a-z][a-z0-9+.-]*:|#|//)", target, re.I):
        return m.group(0)
    path, sep, frag = target.partition("#")
    if path in PAGES:
        return m.group(0)
    resolved = posixpath.normpath(posixpath.join("reference", path))
    return f"{m.group(1)}{REPO}{resolved}{sep}{frag}{m.group(3)}"


def adapt(name, text):
    text = text.replace("\r\n", "\n")
    text, n = COMMENT.subn(NOTE + "\n", text, count=1)
    if n != 1:
        sys.exit(f"{name}: generated-file comment not found")
    # Don't touch links inside code spans or fences: none are expected to be
    # relative links, and the pattern only matches markdown link syntax.
    return LINK.sub(fix_link, text)


# The fork's pages link to GitHub's heading ids and to <a id="..."> anchors.
# GitBook names headings differently (it keeps dots, writes & as "and"), gives
# ids only to ## and ### headings, and drops <a id> anchors. So each link is
# pointed at the GitBook id of its heading, or of the ## or ### section that
# holds its anchor.
HEADING = re.compile(r"^(#{1,6}) (.+)$")
ANCHOR = re.compile(r'<a id="([^"]+)"></a>')


def plain(heading):
    text = ANCHOR.sub("", heading)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return text.replace("`", "").replace("*", "").strip()


def github_id(heading):
    return re.sub(r"[^\w\- ]", "", plain(heading).lower()).replace(" ", "-")


def gitbook_id(heading):
    text = plain(heading).lower().replace("&", "and")
    text = re.sub(r"['\u2019]", "", text)
    text = re.sub(r"[^\w.\-]+", "-", text)
    text = re.sub(r"-{2,}", "-", text).strip("-")
    return "id-" + text if text[:1].isdigit() else text


def anchor_map(text):
    """Map every GitHub id and <a id> on a page to a GitBook id."""
    ids, section, fenced = {}, None, False
    for line in text.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = HEADING.match(line)
        if m and len(m.group(1)) in (2, 3):
            section = gitbook_id(m.group(2))
            ids.setdefault(github_id(m.group(2)), section)
            ids.setdefault(section, section)
        elif m and len(m.group(1)) > 3 and section:
            ids.setdefault(github_id(m.group(2)), section)
        if section:
            for a in ANCHOR.findall(line):
                ids.setdefault(a, section)
    return ids


def fix_anchors(pages):
    maps = {name: anchor_map(text) for name, text in pages.items()}
    missing = []

    for name in pages:
        def fix(m):
            path, _, frag = m.group(2).partition("#")
            page = path or name
            if page not in maps or not frag:
                return m.group(0)
            if frag not in maps[page]:
                missing.append(f"{name}: {m.group(2)}")
                return m.group(0)
            return f"{m.group(1)}{path}#{maps[page][frag]}{m.group(3)}"

        pages[name] = LINK.sub(fix, pages[name])
    if missing:
        sys.exit("links to no heading or anchor:\n" + "\n".join(missing))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]) / "reference"
    dst = Path(__file__).resolve().parent.parent / "reference"
    dst.mkdir(exist_ok=True)
    pages = {name: adapt(name, (src / name).read_text(encoding="utf-8")) for name in GENERATED}
    fix_anchors(pages)
    for name, out in pages.items():
        target = dst / name
        if not target.exists() or target.read_bytes() != out.encode("utf-8"):
            target.write_bytes(out.encode("utf-8"))
            print("updated", name)


if __name__ == "__main__":
    main()
